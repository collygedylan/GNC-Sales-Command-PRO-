  select array_agg(column_row.attname order by column_row.attnum) into columns
  from pg_attribute column_row
  where column_row.attrelid=p_table and column_row.attnum>0 and not column_row.attisdropped
    and column_row.attgenerated='' and column_row.attidentity=''
    and exists(select 1 from jsonb_array_elements(cleaned_rows) as source_row(row_value)
      where row_value ? column_row.attname);
  if not ('unique_id'=any(columns)) then
    raise exception using errcode='22023',message='FAST_ERP_ROW_IDENTITY_INVALID';
  end if;
  execute format('create temp table %I on commit drop as select source_row.ordinality::bigint fast_row_number,typed.*
    from jsonb_array_elements($1) with ordinality source_row(value,ordinality)
    cross join lateral jsonb_populate_record(null::%s,source_row.value) typed',stage_name,p_table)
    using cleaned_rows;
  execute format('create unique index on %I(unique_id)',stage_name);
  update_columns:=array(select column_name from unnest(columns) column_name
    where column_name<>'unique_id' and not (column_name=any(coalesce(p_preserve_columns,'{}'::text[]))));
  quoted_columns:=array_to_string(array(select format('%I',column_name) from unnest(columns) column_name),',');
  update_values:=array_to_string(array(select format('%1$I=excluded.%1$I',column_name)
    from unnest(update_columns) column_name),',');
  changed_predicate:=array_to_string(array(select format('target.%1$I is distinct from excluded.%1$I',column_name)
    from unnest(update_columns) column_name),' or ');
  sql_text:=format('with changed as (
      insert into %s as target(%s) select %s from %I
      on conflict(unique_id) do update set %s where %s
      returning xmax=0 inserted)
    select count(*) filter(where inserted)::integer,count(*) filter(where not inserted)::integer from changed',
    p_table,quoted_columns,quoted_columns,stage_name,update_values,changed_predicate);
  execute sql_text into inserted_rows,updated_rows;
  if p_delete_missing then
    execute format('delete from %s target where not exists(select 1 from %I source where source.unique_id=target.unique_id)%s',
      p_table,stage_name,case when p_table='public.ph_soc_master'::regclass then ' and not private.soc_tag_has_saved_work_v23188(to_jsonb(target))' else '' end);
    get diagnostics deleted_rows=row_count;
  end if;
  return jsonb_build_object('source_rows',jsonb_array_length(cleaned_rows),'inserted_rows',inserted_rows,
    'updated_rows',updated_rows,'unchanged_rows',jsonb_array_length(cleaned_rows)-inserted_rows-updated_rows,
    'deleted_rows',deleted_rows);
end
$function$
;
CREATE OR REPLACE FUNCTION suspend_tag_private.retain_candidate_decision()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare closed_at timestamptz;
begin
 if tg_op='UPDATE' then
  if old.suspend_candidate_group is not null and nullif(current_setting('app.suspend_tag_actor_id',true),'') is null then
   new.suspend_candidate_group:=old.suspend_candidate_group; new.suspend_candidate_state:=old.suspend_candidate_state;
   new.suspend_order_quantity:=old.suspend_order_quantity; new.suspend_origin_uid:=old.suspend_origin_uid;
   if old.suspend_candidate_state in ('replaced','approved','denied','canceled') then
    new.locationcode:=old.locationcode; new.lotcode:=old.lotcode; new.quantityordered:=old.quantityordered;
    new.suspend:=old.suspend; new.suspend_to:=old.suspend_to; new.date_completed:=old.date_completed;
   end if;
  end if;
 end if;
 if new.date_completed is not null and nullif(btrim(new.suspend),'') is null
 and (new.suspend_completed or exists(select 1 from public.ph_productivity_history h where h.event_key='suspend-tag-complete:'||new.unique_id)) then
  insert into private.dock_suspend_closed_lines_v23183 values(new.unique_id,private.dock_order_business_key_v23183(to_jsonb(new)),new.date_completed)
  on conflict(source_uid) do update set business_key=excluded.business_key,completed_at=excluded.completed_at;
  if nullif(new.suspend_origin_uid,'') is not null then
   insert into private.dock_suspend_closed_lines_v23183 values(new.suspend_origin_uid,private.dock_order_business_key_v23183(to_jsonb(new)),new.date_completed)
   on conflict(source_uid) do update set completed_at=excluded.completed_at;
  end if;
 end if;
 select completed_at into closed_at from private.dock_suspend_closed_lines_v23183
 where source_uid=new.unique_id order by completed_at desc limit 1;
 if closed_at is not null then new.suspend:=null; new.suspend_to:=null; new.date_completed:=closed_at; new.status:='completed'; new.completed:=true; new.suspend_completed:=true; end if;
 return new;
end $function$
;
