create or replace function public.reconcile_eval_itemcodes()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  discovered integer := 0;
  alerted integer := 0;
  unassigned_total integer := 0;
begin
  update public.ph_warehouse_assigned_items
  set present_in_drive = false, updated_at = now()
  where assignment_key is not null;

  with drive_codes as (
    select
      upper(btrim(itemcode)) as itemcode_normalized,
      lower(regexp_replace(btrim(coalesce(genusname, '')), '[[:space:]]+', ' ', 'g')) as genusname_normalized,
      max(genusname) as genusname,
      max(commonname) as commonname,
      max(contsize) as contsize,
      max(locationcode) as locationcode
    from public.ph_master_inventory
    where nullif(btrim(coalesce(itemcode, '')), '') is not null
    group by
      upper(btrim(itemcode)),
      lower(regexp_replace(btrim(coalesce(genusname, '')), '[[:space:]]+', ' ', 'g'))
  ), written as (
    insert into public.ph_warehouse_assigned_items (
      unique_id, itemcode, itemcode_normalized, genusname, genusname_normalized,
      concat, assignment_key, commonname, contsize, locationcode, source,
      first_seen_at, last_seen_at, present_in_drive, raw_row, updated_at
    )
    select
      'eval-itemcode-genus-' || md5(private.normalize_eval_assignment_key(d.itemcode_normalized, d.genusname)),
      d.itemcode_normalized,
      d.itemcode_normalized,
      d.genusname,
      d.genusname_normalized,
      d.itemcode_normalized || d.genusname,
      private.normalize_eval_assignment_key(d.itemcode_normalized, d.genusname),
      d.commonname,
      d.contsize,
      d.locationcode,
      'supabase_drive_reconcile',
      now(),
      now(),
      true,
      jsonb_build_object('authority', 'supabase', 'scope', 'itemcode_genus'),
      now()
    from drive_codes d
    on conflict (assignment_key) where assignment_key is not null
    do update set
      itemcode = excluded.itemcode,
      itemcode_normalized = excluded.itemcode_normalized,
      genusname = excluded.genusname,
      genusname_normalized = excluded.genusname_normalized,
      concat = excluded.concat,
      commonname = excluded.commonname,
      contsize = excluded.contsize,
      locationcode = excluded.locationcode,
      source = case
        when public.ph_warehouse_assigned_items.source = 'google_sheet_cutover_20260820'
          then public.ph_warehouse_assigned_items.source
        else 'supabase_drive_reconcile'
      end,
      last_seen_at = now(),
      present_in_drive = true,
      updated_at = now()
    returning (xmax = 0) as was_inserted
  )
  select count(*) filter (where was_inserted) into discovered from written;

  with needs_alert as (
    select id, itemcode_normalized, genusname, assignment_key
    from public.ph_warehouse_assigned_items
    where present_in_drive
      and nullif(btrim(coalesce(assignedto, '')), '') is null
      and unassigned_notified_at is null
    for update
  ), queued as (
    insert into public.ph_request_delivery_outbox (
      event_key, event_type, payload, status
    )
    select
      'eval-unassigned:' || md5(assignment_key),
      'eval_assignment_unassigned',
      jsonb_build_object(
        'itemcode', itemcode_normalized,
        'genusname', genusname,
        'assignment_key', assignment_key,
        'manager_usernames', jsonb_build_array('dylan_collyge', 'megan_kelly')
      ),
      'pending'
    from needs_alert
    on conflict (event_key) do update set
      status = case
        when public.ph_request_delivery_outbox.status = 'delivered' then 'pending'
        else public.ph_request_delivery_outbox.status
      end,
      next_attempt_at = now(),
      delivered_at = null,
      sanitized_error_code = null
    returning event_key
  )
  select count(*) into alerted from queued;

  update public.ph_warehouse_assigned_items
  set unassigned_notified_at = now(), updated_at = now()
  where present_in_drive
    and nullif(btrim(coalesce(assignedto, '')), '') is null
    and unassigned_notified_at is null;

  select count(*) into unassigned_total
  from public.ph_warehouse_assigned_items
  where present_in_drive
    and nullif(btrim(coalesce(assignedto, '')), '') is null;

  return jsonb_build_object(
    'discovered', discovered,
    'alerts_queued', alerted,
    'unassigned_count', unassigned_total
  );
end;
$$;

create or replace function public.set_eval_itemcode_assignment(
  itemcode text,
  genusname text,
  assignedto text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_code text := upper(btrim(coalesce(itemcode, '')));
  resolved_genus text := nullif(btrim(coalesce(genusname, '')), '');
  normalized_genus text;
  normalized_key text;
  requested_assignee text := nullif(lower(btrim(coalesce(assignedto, ''))), '');
  canonical_assignee text;
  manager_username text;
  drive_row record;
  assignment public.ph_warehouse_assigned_items%rowtype;
begin
  if not private.can_manage_eval_assignments() then
    raise exception using errcode = '42501', message = 'EVAL_ASSIGNMENT_FORBIDDEN';
  end if;
  if normalized_code = '' then
    raise exception using errcode = '22023', message = 'ITEMCODE_REQUIRED';
  end if;

  if requested_assignee = 'charey_robertson' then
    requested_assignee := 'charley_robertson';
  end if;

  if resolved_genus is null then
    select min(x.genusname) into resolved_genus
    from (
      select max(mi.genusname) as genusname
      from public.ph_master_inventory mi
      where upper(btrim(coalesce(mi.itemcode, ''))) = normalized_code
      group by lower(regexp_replace(btrim(coalesce(mi.genusname, '')), '[[:space:]]+', ' ', 'g'))
    ) x
    having count(*) = 1;
  end if;

  if resolved_genus is null then
    select min(a.genusname) into resolved_genus
    from public.ph_warehouse_assigned_items a
    where a.itemcode_normalized = normalized_code
    having count(distinct a.genusname_normalized) = 1;
  end if;

  if resolved_genus is null then
    raise exception using errcode = '22023', message = 'GENUSNAME_REQUIRED';
  end if;

  normalized_genus := lower(regexp_replace(btrim(resolved_genus), '[[:space:]]+', ' ', 'g'));
  normalized_key := private.normalize_eval_assignment_key(normalized_code, resolved_genus);
  manager_username := (private.current_active_profile()).username;

  if requested_assignee is not null then
    select u.username into canonical_assignee
    from public.ph_eval_assignment_users u
    where u.active
      and lower(btrim(u.username)) = requested_assignee
    limit 1;
    if canonical_assignee is null then
      raise exception using errcode = '22023', message = 'ASSIGNEE_NOT_IN_EVAL_ROSTER';
    end if;
  end if;

  select
    max(mi.genusname) as genusname,
    max(mi.commonname) as commonname,
    max(mi.contsize) as contsize,
    max(mi.locationcode) as locationcode
  into drive_row
  from public.ph_master_inventory mi
  where upper(btrim(coalesce(mi.itemcode, ''))) = normalized_code
    and lower(regexp_replace(btrim(coalesce(mi.genusname, '')), '[[:space:]]+', ' ', 'g')) = normalized_genus;

  resolved_genus := coalesce(nullif(btrim(drive_row.genusname), ''), resolved_genus);

  insert into public.ph_warehouse_assigned_items (
    unique_id, itemcode, itemcode_normalized, genusname, genusname_normalized,
    concat, assignment_key, assignedto, assigned_by, assigned_at,
    commonname, contsize, locationcode, first_seen_at, last_seen_at,
    present_in_drive, source, raw_row, updated_at, unassigned_notified_at
  ) values (
    'eval-itemcode-genus-' || md5(normalized_key),
    normalized_code,
    normalized_code,
    resolved_genus,
    normalized_genus,
    normalized_code || resolved_genus,
    normalized_key,
    canonical_assignee,
    manager_username,
    case when canonical_assignee is null then null else now() end,
    drive_row.commonname,
    drive_row.contsize,
    drive_row.locationcode,
    now(),
    now(),
    exists (
      select 1
      from public.ph_master_inventory mi
      where upper(btrim(coalesce(mi.itemcode, ''))) = normalized_code
        and lower(regexp_replace(btrim(coalesce(mi.genusname, '')), '[[:space:]]+', ' ', 'g')) = normalized_genus
    ),
    'supabase_assignment_manager',
    jsonb_build_object('authority', 'supabase', 'scope', 'itemcode_genus'),
    now(),
    case when canonical_assignee is null then null else now() end
  )
  on conflict (assignment_key) where assignment_key is not null
  do update set
    itemcode = excluded.itemcode,
    itemcode_normalized = excluded.itemcode_normalized,
    genusname = excluded.genusname,
    genusname_normalized = excluded.genusname_normalized,
    concat = excluded.concat,
    assignedto = excluded.assignedto,
    assigned_by = excluded.assigned_by,
    assigned_at = excluded.assigned_at,
    commonname = coalesce(excluded.commonname, public.ph_warehouse_assigned_items.commonname),
    contsize = coalesce(excluded.contsize, public.ph_warehouse_assigned_items.contsize),
    locationcode = coalesce(excluded.locationcode, public.ph_warehouse_assigned_items.locationcode),
    source = excluded.source,
    raw_row = excluded.raw_row,
    updated_at = now(),
    unassigned_notified_at = case
      when excluded.assignedto is null
           and nullif(btrim(coalesce(public.ph_warehouse_assigned_items.assignedto, '')), '') is not null
        then null
      when excluded.assignedto is not null then now()
      else public.ph_warehouse_assigned_items.unassigned_notified_at
    end
  returning * into assignment;

  if canonical_assignee is null and assignment.unassigned_notified_at is null then
    insert into public.ph_request_delivery_outbox (
      event_key, event_type, payload, status
    ) values (
      'eval-unassigned:' || md5(normalized_key),
      'eval_assignment_unassigned',
      jsonb_build_object(
        'itemcode', normalized_code,
        'genusname', resolved_genus,
        'assignment_key', normalized_key,
        'manager_usernames', jsonb_build_array('dylan_collyge', 'megan_kelly')
      ),
      'pending'
    )
    on conflict (event_key) do update set
      status = 'pending',
      next_attempt_at = now(),
      delivered_at = null,
      sanitized_error_code = null;

    update public.ph_warehouse_assigned_items
    set unassigned_notified_at = now(), updated_at = now()
    where id = assignment.id
    returning * into assignment;
  end if;

  return to_jsonb(assignment);
end;
$$;

create or replace function public.set_eval_itemcode_assignment(
  itemcode text,
  assignedto text
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  resolved_genus text;
begin
  select min(x.genusname) into resolved_genus
  from (
    select max(mi.genusname) as genusname
    from public.ph_master_inventory mi
    where upper(btrim(coalesce(mi.itemcode, ''))) = upper(btrim(coalesce(itemcode, '')))
    group by lower(regexp_replace(btrim(coalesce(mi.genusname, '')), '[[:space:]]+', ' ', 'g'))
  ) x
  having count(*) = 1;

  if resolved_genus is null then
    raise exception using errcode = '22023', message = 'GENUSNAME_REQUIRED';
  end if;

  return public.set_eval_itemcode_assignment(itemcode, resolved_genus, assignedto);
end;
$$;

