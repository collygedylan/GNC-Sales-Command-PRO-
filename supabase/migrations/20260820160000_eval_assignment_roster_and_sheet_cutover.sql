create or replace function private.normalize_eval_assignment_key(
  itemcode text,
  genusname text
)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when nullif(btrim(coalesce(itemcode, '')), '') is null then null
    else upper(btrim(itemcode)) || '|' ||
         lower(regexp_replace(btrim(coalesce(genusname, '')), '[[:space:]]+', ' ', 'g'))
  end
$$;

alter table public.ph_warehouse_assigned_items
  add column if not exists genusname_normalized text,
  add column if not exists assignment_key text;

with drive_codes as (
  select
    upper(btrim(itemcode)) as itemcode_normalized,
    max(genusname) as genusname
  from public.ph_master_inventory
  where nullif(btrim(coalesce(itemcode, '')), '') is not null
  group by upper(btrim(itemcode))
)
update public.ph_warehouse_assigned_items a
set
  genusname = coalesce(nullif(btrim(a.genusname), ''), d.genusname),
  genusname_normalized = lower(regexp_replace(
    btrim(coalesce(nullif(btrim(a.genusname), ''), d.genusname, '')),
    '[[:space:]]+', ' ', 'g'
  )),
  concat = upper(btrim(a.itemcode_normalized)) || coalesce(nullif(btrim(a.genusname), ''), d.genusname, ''),
  assignment_key = private.normalize_eval_assignment_key(
    a.itemcode_normalized,
    coalesce(nullif(btrim(a.genusname), ''), d.genusname, '')
  ),
  updated_at = now()
from drive_codes d
where d.itemcode_normalized = upper(btrim(coalesce(a.itemcode_normalized, a.itemcode, '')));

update public.ph_warehouse_assigned_items
set
  genusname_normalized = lower(regexp_replace(btrim(coalesce(genusname, '')), '[[:space:]]+', ' ', 'g')),
  concat = upper(btrim(coalesce(itemcode_normalized, itemcode, ''))) || coalesce(genusname, ''),
  assignment_key = private.normalize_eval_assignment_key(
    coalesce(itemcode_normalized, itemcode),
    genusname
  ),
  updated_at = now()
where assignment_key is null
  and nullif(btrim(coalesce(itemcode_normalized, itemcode, '')), '') is not null;

