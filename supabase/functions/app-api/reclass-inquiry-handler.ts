import type { readSupabaseOrAppSessionFromRequest } from "../_shared/app-auth.ts";
import { jsonObject } from "../../../services/database-contract-runtime.ts";
import { RECLASS_EDITABLE_FIELDS_POLICY, validateReclassEditableFieldProposals } from "../../../services/reclassEditableFields.ts";
import { validateReclassSmartShieldProposals } from "../../../services/reclassSmartShield.ts";
import { validateReclassShearedProposals } from "../../../services/reclassSheared.ts";
import { authorizeReclassInquiry, enqueueReclassInquiry, invokeReclassInquiryRpc, recoverReclassInquiryReceipt,
  type InquiryDatabase, type InquiryRecord } from "./reclass-inquiry-transport.ts";

type Session = Awaited<ReturnType<typeof readSupabaseOrAppSessionFromRequest>>;
export type ReclassInquiryDependencies = {
  db: InquiryDatabase;
  resolveActiveSessionProfile: Function;
  normalizeUsername: Function;
  sanitizePayload: Function;
  jsonResponse: Function;
  errorResponse: Function;
  inquiryError: Function;
  seasonPriorityError: Function;
  dispatchDelivery: Function;
};
type InquiryContext = { dependencies: ReclassInquiryDependencies; actor: InquiryRecord; actorUsername: string; payload: InquiryRecord };

async function handleSeasonPriorityInquiry(context: InquiryContext, operation: string): Promise<Response | null> {
  const { dependencies: d, actor, payload } = context;
  if (operation === "season_priority_list") {
    const assignedTo = String(payload.assignedTo || payload.assigned_to || "all").trim().slice(0, 120);
    const { data, error } = await invokeReclassInquiryRpc(d.db, "manager_season_priority_list_v1", {
      p_actor_id: String(actor.id), p_assigned_to: assignedTo,
    });
    return error ? d.seasonPriorityError(error.message || "") : d.jsonResponse(data && typeof data === "object" ? data : { ok: false, rows: [] });
  }
  if (operation === "season_priority_submit") {
    const expectedPriority = Number(payload.expectedPriority ?? payload.expected_priority);
    const { data, error } = await invokeReclassInquiryRpc(d.db, "submit_manager_season_priority_v2", {
      p_actor_id: String(actor.id), p_source_unique_id: String(payload.sourceUid || payload.source_uid || "").trim(),
      p_expected_priority: Number.isInteger(expectedPriority) ? expectedPriority : 0,
      p_scope_fingerprint: String(payload.scopeFingerprint || payload.scope_fingerprint || "").trim().toLowerCase(),
      p_idempotency_token: String(payload.idempotencyToken || payload.idempotency_token || "").trim(),
    });
    return error ? d.seasonPriorityError(error.message || "") : d.jsonResponse(data && typeof data === "object" ? data : { ok: false, lifecycleStatus: "delivery_failed" });
  }
  if (operation !== "season_priority_state") return null;
  const itemcodes = Array.isArray(payload.itemcodes) ? payload.itemcodes.slice(0, 101).map(value => String(value || "").trim()).filter(Boolean) : null;
  const { data, error } = await invokeReclassInquiryRpc(d.db, "manager_season_priority_state_v1", {
    p_actor_id: String(actor.id), ...(itemcodes ? { p_itemcodes: itemcodes } : {}),
  });
  return error ? d.seasonPriorityError(error.message || "") : d.jsonResponse(data && typeof data === "object" ? data : { ok: false, requests: [] });
}

function validateInquiryCreate(payload: InquiryRecord, d: ReclassInquiryDependencies): Response | null {
  if (payload.workflowPolicyVersion === RECLASS_EDITABLE_FIELDS_POLICY && payload.sourceContext != null
    && (typeof payload.sourceContext !== "object" || Array.isArray(payload.sourceContext))) {
    return d.inquiryError("DRIVE_RECLASS_V7_SOURCE_CONTEXT_INVALID");
  }
  if (Object.hasOwn(jsonObject(payload.transaction), "seasonPriority")) {
    return d.errorResponse("Season Priority contracts are generated by the protected Manager action.", 400, { code: "SEASON_PRIORITY_MARKER_RESERVED" });
  }
  return null;
}

async function createReclassInquiry(context: InquiryContext): Promise<Response> {
  const { dependencies: d, actor, actorUsername, payload } = context;
  const invalid = validateInquiryCreate(payload, d);
  if (invalid) return invalid;
  const protectedPayload = { ...d.sanitizePayload(payload), actorUsername,
    reclassExplanations: payload.reclassExplanations ?? {} };
  try {
    validateReclassShearedProposals(protectedPayload);
    validateReclassSmartShieldProposals(protectedPayload);
    validateReclassEditableFieldProposals(protectedPayload);
    await authorizeReclassInquiry(d.db, { ...actor, username: actorUsername }, protectedPayload);
    const result = await enqueueReclassInquiry(d.db, protectedPayload);
    return d.jsonResponse(await d.dispatchDelivery(result, actorUsername, String(protectedPayload.idempotencyToken || "")));
  } catch (error) {
    return d.inquiryError(error instanceof Error ? error.message : "DRIVE_RECLASS_V5_PAYLOAD_INVALID");
  }
}

async function readReclassInquiry(context: InquiryContext, operation: string): Promise<Response> {
  const { dependencies: d, actorUsername, payload } = context;
  const token = String(payload.idempotencyToken || payload.idempotency_token || "").trim();
  const name = operation === "status" ? "get_drive_reclass_inquiry_status_v1"
    : operation === "retry" ? "retry_drive_reclass_inquiry_v1" : "";
  if (!name) return d.errorResponse("Unsupported Reclass operation.", 400, { code: "DRIVE_RECLASS_OPERATION_INVALID" });
  const { data, error } = await invokeReclassInquiryRpc(d.db, name, { p_actor_username: actorUsername, p_idempotency_token: token });
  if (error) return d.inquiryError(error.message || "");
  const saved = jsonObject(data);
  const result = operation === "retry" ? await d.dispatchDelivery(saved, actorUsername, token) : saved;
  await recoverReclassInquiryReceipt(d.db, result, actorUsername, d.normalizeUsername);
  return d.jsonResponse(Object.keys(result).length ? result : { ok: false, status: "missing" });
}

function inquiryActorMatchesSession(session: NonNullable<Session>, actor: InquiryRecord, normalize: Function): boolean {
  const username = normalize(String(actor.username || ""));
  const sessionUsername = normalize(String(session.username || session.displayName || ""));
  return !!username && !!actor.id && (!session.authUserId || actor.id === session.authUserId)
    && (!sessionUsername || username === sessionUsername);
}

export async function executeReclassInquiryAction(
  session: Session, payload: InquiryRecord, dependencies: ReclassInquiryDependencies,
): Promise<Response> {
  const d = dependencies;
  if (!session) return d.errorResponse("Authentication required.", 401, { code: "AUTH_REQUIRED" });
  if (session.mustChangePassword) return d.errorResponse("Password change required.", 403, { code: "PASSWORD_CHANGE_REQUIRED" });
  const actor = await d.resolveActiveSessionProfile(session).catch(() => null);
  if (!actor) return d.errorResponse("An active, unlocked app profile is required.", 403, { code: "PROFILE_NOT_ACTIVE" });
  if (!inquiryActorMatchesSession(session, actor, d.normalizeUsername)) {
    return d.errorResponse("Authenticated user identity is required.", 403, { code: "PROFILE_IDENTITY_REQUIRED" });
  }
  const context = { dependencies: d, actor, actorUsername: d.normalizeUsername(String(actor.username)), payload };
  const operation = String(payload.operation || "create").trim().toLowerCase();
  try {
    const priority = await handleSeasonPriorityInquiry(context, operation);
    if (priority) return priority;
    return operation === "create" ? await createReclassInquiry(context) : await readReclassInquiry(context, operation);
  } catch {
    return d.inquiryError("DRIVE_RECLASS_SERVICE_UNAVAILABLE");
  }
}
