create or replace function public.v2_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.v2_eval_assignment_rules (
  id bigint generated by default as identity primary key,
  source_file text not null default 'ALL IN ONE',
  source_sheet text not null default 'ALL IN ONE',
  sheet_row_number integer not null,
  assignedto_raw text not null,
  assignedto text not null,
  warehousei text,
  itemcode text,
  contsize text,
  commonname text,
  locationcode text,
  source text,
  genusname text,
  active boolean not null default true,
  notes text,
  imported_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint v2_eval_assignment_rules_unique_source_row
    unique (source_file, source_sheet, sheet_row_number)
);

drop trigger if exists trg_v2_eval_assignment_rules_updated_at
on public.v2_eval_assignment_rules;

create trigger trg_v2_eval_assignment_rules_updated_at
before update on public.v2_eval_assignment_rules
for each row execute function public.v2_set_updated_at();

create table if not exists public.v2_eval_assignment_rules_import (
  import_id bigint generated by default as identity primary key,
  "AssignedTo" text,
  "WAREHOUSEI" text,
  "ITEMCODE" text,
  "CONTSIZE" text,
  "COMMONNAME" text,
  "LOCATIONCODE" text,
  "SOURCE" text,
  "GENUSNAME" text,
  imported_at timestamptz not null default now()
);

alter table public.v2_eval_assignment_rules_import enable row level security;
revoke all on public.v2_eval_assignment_rules_import from anon, authenticated;

create index if not exists idx_eval_rules_active_itemcode
  on public.v2_eval_assignment_rules (itemcode) where active and itemcode is not null;
create index if not exists idx_eval_rules_active_commonname
  on public.v2_eval_assignment_rules (commonname) where active and commonname is not null;
create index if not exists idx_eval_rules_active_genusname
  on public.v2_eval_assignment_rules (genusname) where active and genusname is not null;
create index if not exists idx_eval_rules_active_locationcode
  on public.v2_eval_assignment_rules (locationcode) where active and locationcode is not null;
create index if not exists idx_eval_rules_active_contsize
  on public.v2_eval_assignment_rules (contsize) where active and contsize is not null;
create index if not exists idx_eval_rules_active_source
  on public.v2_eval_assignment_rules (source) where active and source is not null;
create index if not exists idx_eval_rules_active_warehousei
  on public.v2_eval_assignment_rules (warehousei) where active and warehousei is not null;
create index if not exists idx_eval_rules_active_assignedto
  on public.v2_eval_assignment_rules (assignedto) where active;

alter table public.v2_eval_assignment_rules enable row level security;

drop policy if exists "Authenticated users can read active eval assignment rules"
on public.v2_eval_assignment_rules;

create policy "Authenticated users can read active eval assignment rules"
on public.v2_eval_assignment_rules
for select
to authenticated
using (active = true);

drop policy if exists "Anon app can read active eval assignment rules"
on public.v2_eval_assignment_rules;

create policy "Anon app can read active eval assignment rules"
on public.v2_eval_assignment_rules
for select
to anon
using (active = true);

grant select on public.v2_eval_assignment_rules to authenticated;
grant select on public.v2_eval_assignment_rules to anon;

