import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

export async function buildPhotoArchiveReceiver() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('../src/services/photo-archive-receiver.mjs', import.meta.url))],
    bundle: true, write: false, format: 'iife', globalName: 'AgDataPhotoArchiveReceiver',
    platform: 'neutral', target: 'es2020', legalComments: 'none',
    banner: { js: '// Generated by scripts/build-photo-archive-receiver.mjs; edit photo-archive-receiver.mjs.' },
  });
  return result.outputFiles[0].text;
}
