import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { sandboxDatabaseTypesPath } from './sandbox-database-workspace.mjs';

export const generatedDatabaseTypesPath = 'supabase/functions/_shared/database.types.ts';
const partsDirectory = entry => path.posix.join(path.posix.dirname(entry), 'database-types');
const partsPath = partsDirectory(generatedDatabaseTypesPath);
const ownedPart = /^part-[0-9]{4}\.ts$/;
const partHeader = '// Generated by the Supabase database type generator.\n';
const shapeMarker = '/* db-shape */';
const partBudget = 360;
const lineCount = source => source.split('\n').length;
const normalize = source => source.replaceAll('\r\n', '\n').replace(/\n*$/, '\n');
const databaseType = sourceFile => sourceFile.statements.find(node => ts.isTypeAliasDeclaration(node)
  && node.name.text === 'Database')?.type;

function groupsFor(entries) {
  const groups = [];
  let group = '';
  for (const entry of entries) {
    if (group && lineCount(group + entry) > partBudget) {
      groups.push(group);
      group = '';
    }
    group += entry;
  }
  if (group) groups.push(group);
  return groups;
}

function referencedImports(shape) {
  const file = ts.createSourceFile('part.ts', 'type Shape = ' + shape, ts.ScriptTarget.Latest, true);
  const names = new Set();
  function visit(node) {
    if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) names.add(node.typeName.text);
    ts.forEachChild(node, visit);
  }
  visit(file);
  const imports = ['Database', 'Json'].filter(name => names.has(name));
  return imports.length ? `import type { ${imports.join(', ')} } from "../database.types.ts";\n` : '';
}

function writeShapePart(parts, source) {
  const name = `part-${String(parts.size + 1).padStart(4, '0')}.ts`;
  const body = source.replace(/import\("\.\/database-types\/(part-[0-9]{4}\.ts)"\)\.Shape/g,
    (_, reference) => `import("./${reference}").Shape`);
  const content = partHeader + referencedImports(body) + 'export type Shape = ' + body + '\n';
  if (!ownedPart.test(name) || lineCount(content) > 400) throw new Error('DATABASE_TYPES_PART_TOO_LARGE');
  parts.set(path.posix.join(partsPath, name), content);
  return `import("./database-types/${name}").Shape`;
}

function packLiteral(node, source, file, parts) {
  const entries = [];
  let cursor = node.getStart(file) + 1;
  for (const member of node.members) {
    if (!ts.isPropertySignature(member) || !member.type) throw new Error('DATABASE_TYPES_LITERAL_MEMBER_UNSUPPORTED');
    entries.push(source.slice(cursor, member.type.getStart(file)) + packType(member.type, source, file, parts)
      + source.slice(member.type.end, member.end));
    cursor = member.end;
  }
  entries.push(source.slice(cursor, node.end - 1));
  const refs = groupsFor(entries).map(group => writeShapePart(parts, '{' + group + '}'));
  return `${shapeMarker} (${refs.join(' & ')})`;
}

function packType(node, source, file, parts) {
  const start = node.getStart(file);
  const raw = source.slice(start, node.end);
  if (lineCount(raw) <= partBudget) return raw;
  if (ts.isTypeLiteralNode(node)) return packLiteral(node, source, file, parts);
  let cursor = start;
  let output = '';
  ts.forEachChild(node, child => {
    if (!ts.isTypeNode(child)) return;
    output += source.slice(cursor, child.getStart(file)) + packType(child, source, file, parts);
    cursor = child.end;
  });
  return output + source.slice(cursor, node.end);
}

function artifactParts(parts, entry) {
  if (entry === generatedDatabaseTypesPath) return parts;
  if (entry !== sandboxDatabaseTypesPath) throw new Error('DATABASE_TYPES_ARTIFACT_UNSUPPORTED');
  const result = new Map();
  for (const [file, content] of parts) {
    if (file === generatedDatabaseTypesPath) result.set(entry, content);
    else result.set(path.posix.join(partsDirectory(entry), path.posix.basename(file)),
      content.replace('from "../database.types.ts";\n', 'from "../sandbox.database.types.ts";\n'));
  }
  return result;
}

export function packGeneratedDatabaseTypes(nativeSource, entry = generatedDatabaseTypesPath) {
  const source = normalize(nativeSource);
  const file = ts.createSourceFile('database.types.ts', source, ts.ScriptTarget.Latest, true);
  const type = databaseType(file);
  if (file.parseDiagnostics.length || !type || source.includes(shapeMarker)) throw new Error('DATABASE_TYPES_NATIVE_INVALID');
  const parts = new Map();
  const packed = packType(type, source, file, parts);
  parts.set(generatedDatabaseTypesPath, source.slice(0, type.getStart(file)) + packed + source.slice(type.end));
  return artifactParts(parts, entry);
}

const shapeRef = /import\("\.\/(?:database-types\/)?(part-[0-9]{4}\.ts)"\)\.Shape/g;
const shapeGroup = /\/\* db-shape \*\/ \((import\("\.\/(?:database-types\/)?part-[0-9]{4}\.ts"\)\.Shape(?: & import\("\.\/(?:database-types\/)?part-[0-9]{4}\.ts"\)\.Shape)*)\)/g;

function expandShape(source, readPart, seen) {
  const expanded = source.replace(shapeGroup, (_, references) => {
    const groups = [...references.matchAll(shapeRef)].map(([, name]) => {
      if (seen.has(name)) throw new Error(`DATABASE_TYPES_REPEATED_PART: ${name}`);
      seen.add(name);
      const content = normalize(readPart(name));
      const literal = content.match(/^\/\/ Generated by the Supabase database type generator\.\n(?:import type \{ [\w, ]+ \} from "\.\.\/(?:sandbox\.)?database\.types\.ts";\n)?export type Shape = (\{[\s\S]*\})\n$/)?.[1];
      if (!literal) throw new Error(`DATABASE_TYPES_INVALID_PART: ${name}`);
      return expandShape(literal.slice(1, -1), readPart, seen);
    });
    return '{' + groups.join('') + '}';
  });
  if (expanded.includes(shapeMarker)) throw new Error('DATABASE_TYPES_INVALID_PART_REFERENCE');
  return expanded;
}

export function readGeneratedDatabaseTypes(root, relativePath = generatedDatabaseTypesPath) {
  const source = normalize(readFileSync(path.join(root, relativePath), 'utf8'));
  return expandShape(source, name => readFileSync(path.join(root, partsDirectory(relativePath), name), 'utf8'), new Set());
}

function existingParts(directory) {
  if (!existsSync(directory)) return [];
  if (!lstatSync(directory).isDirectory()) throw new Error('DATABASE_TYPES_PART_DIRECTORY_INVALID');
  return readdirSync(directory, { withFileTypes: true });
}

export function verifyGeneratedDatabaseTypes(root, nativeSource, entry = generatedDatabaseTypesPath) {
  const expected = packGeneratedDatabaseTypes(nativeSource, entry);
  const parts = partsDirectory(entry);
  for (const [file, content] of expected) {
    if (normalize(readFileSync(path.join(root, file), 'utf8')) !== content) throw new Error(`DATABASE_TYPES_OUT_OF_DATE: ${file}`);
  }
  for (const file of existingParts(path.join(root, parts))) {
    if (!file.isFile() || !expected.has(path.posix.join(parts, file.name))) {
      throw new Error(`DATABASE_TYPES_OUT_OF_DATE: unexpected part ${file.name}`);
    }
  }
  if (readGeneratedDatabaseTypes(root, entry) !== normalize(nativeSource)) throw new Error('DATABASE_TYPES_ROUND_TRIP_MISMATCH');
}

export function writeGeneratedDatabaseTypes(root, nativeSource, entry = generatedDatabaseTypesPath) {
  const expected = packGeneratedDatabaseTypes(nativeSource, entry);
  const parts = partsDirectory(entry);
  const directory = path.join(root, parts);
  const present = existingParts(directory);
  if (present.some(file => !file.isFile() || !ownedPart.test(file.name))) throw new Error('DATABASE_TYPES_UNOWNED_PART');
  const stale = present.filter(file => !expected.has(path.posix.join(parts, file.name)));
  mkdirSync(directory, { recursive: true });
  for (const [file, content] of expected) writeFileSync(path.join(root, file), content);
  for (const file of stale) rmSync(path.join(directory, file.name));
  verifyGeneratedDatabaseTypes(root, nativeSource, entry);
}
